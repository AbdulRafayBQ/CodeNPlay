  function translateQuestion(str) {
    if (!str) return str;
    if (window.I18N && window.I18N.getLang() !== 'ur') return str;
    if (Q_MAP[str]) return Q_MAP[str];

    // Pattern fallback for questions
    let s = str;
    s = s.replace(/^Which tag creates /i, 'Konsa tag banata hai ');
    s = s.replace(/^Which tag makes /i, 'Konsa tag banata hai ');
    s = s.replace(/^Which tag is /i, 'Konsa tag hai ');
    s = s.replace(/^Which tag /i, 'Konsa tag ');
    s = s.replace(/^Which property sets /i, 'Konsi property set karti hai ');
    s = s.replace(/^Which property /i, 'Konsi property ');
    s = s.replace(/^Which selector /i, 'Konsa selector ');
    s = s.replace(/^Which operator /i, 'Konsa operator ');
    s = s.replace(/^Which keyword /i, 'Konsa keyword ');
    s = s.replace(/^How do you /i, 'Aap kaise karte hain ');
    s = s.replace(/^What does /i, 'Kya karta hai ');
    s = s.replace(/^Make an? /i, 'Banao ');
    s = s.replace(/^Write an? /i, 'Likho ');
    s = s.replace(/^Print /i, 'Print karo ');
    s = s.replace(/^Create /i, 'Banao ');
    s = s.replace(/ that says /i, ' jo kahe ');
    s = s.replace(/ and under it add /i, ' aur uske neeche add karo ');
    s = s.replace(/ with the /i, ' ke sath ');
    return s;
  }

